export type HistoryKey = keyof typeof ar;
export const HISTORY_MESSAGES: Record<Lang, Record<HistoryKey, string>> = { ar, en };

export function hT(lang: Lang, key: HistoryKey, vars?: Record<string, string | number>): string {
  let s: string = HISTORY_MESSAGES[lang][key];
  for (const [k, v] of Object.entries(vars ?? {})) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
