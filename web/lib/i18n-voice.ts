export const VOICE_MESSAGES: Record<Lang, Record<VoiceKey, string>> = { ar, en };

export function voiceText(lang: Lang, key: VoiceKey, vars?: Record<string, string>): string {
  let s: string = VOICE_MESSAGES[lang][key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}
