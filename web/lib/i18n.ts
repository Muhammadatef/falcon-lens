export const MESSAGES: Record<Lang, Record<MessageKey, string>> = { ar, en };

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  let s: string = MESSAGES[lang][key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** Looks up a dynamic key (e.g. `tool.${name}`), falling back to the raw value as plain text. */
export function translateMaybe(lang: Lang, prefix: string, value: string): string {
  const key = `${prefix}.${value}`;
  return key in MESSAGES[lang] ? MESSAGES[lang][key as MessageKey] : value;
}

/** Picks the reader's language from a bilingual API object, falling back to the other one. */
export function pick(lang: Lang, value: { ar?: string; en?: string } | null | undefined): string {
  if (!value) return "";
  return (lang === "ar" ? value.ar || value.en : value.en || value.ar) ?? "";
}

export const dirOf = (lang: Lang): "rtl" | "ltr" => (lang === "ar" ? "rtl" : "ltr");

/** Western digits in both languages (DESIGN.md §3). */
export function timeFormat(lang: Lang, withDate = false): Intl.DateTimeFormat {
  return new Intl.DateTimeFormat(lang === "ar" ? "ar-AE-u-nu-latn" : "en-GB", {
    ...(withDate ? { day: "numeric", month: "short" } : {}),
    hour: "2-digit",
    minute: "2-digit",
    timeZone: "Asia/Dubai",
    hour12: false,
  });
}

export function formatTime(lang: Lang, iso: string | null | undefined, withDate = false): string {
  if (!iso) return "";
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? "" : timeFormat(lang, withDate).format(d);
}
