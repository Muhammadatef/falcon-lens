#!/usr/bin/env node
/**
 * Reads the vendored tool logos (public/logos/tools/*.svg, unmodified Simple Icons files) and their metadata
 * (public/logos/tools/logos.json) and writes:
 *   lib/tool-logos.gen.ts                 path data + brand colour per slug, for inline rendering under the strict CSP
 *   public/logos/tools/LOGOS_LICENSES.md  one row per vendored file: source, licence, date
 * Run after adding or updating a logo: `node scripts/gen-tool-logos.mjs`. tests/unit/tool-logos.test.ts fails if stale.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(web, "public", "logos", "tools");
const meta = JSON.parse(readFileSync(join(dir, "logos.json"), "utf8"));
const files = readdirSync(dir).filter((f) => f.endsWith(".svg")).sort();
const bySlug = new Map(meta.icons.map((i) => [i.slug, i]));

const entries = files.map((f) => {
  const slug = f.replace(/\.svg$/, "");
  const m = bySlug.get(slug);
  if (!m) throw new Error(`no metadata for ${f} in logos.json`);
  const svg = readFileSync(join(dir, f), "utf8");
  const d = [...svg.matchAll(/<path d="([^"]+)"/g)].map((x) => x[1]);
  if (d.length !== 1 || !svg.includes('viewBox="0 0 24 24"')) throw new Error(`${f}: expected one path on a 24 px grid`);
  return { slug, title: m.title, hex: `#${m.hex}`, d: d[0] };
});
for (const i of meta.icons) if (!files.includes(`${i.slug}.svg`)) throw new Error(`logos.json lists ${i.slug} but the file is missing`);

const ts = `/* Generated by scripts/gen-tool-logos.mjs from public/logos/tools. Do not edit by hand. */
export interface LogoPath { title: string; hex: string; d: string }
export const LOGO_PATHS = ${JSON.stringify(Object.fromEntries(entries.map((e) => [e.slug, { title: e.title, hex: e.hex, d: e.d }])), null, 2)} as const satisfies Record<string, LogoPath>;
export type LogoSlug = keyof typeof LOGO_PATHS;
`;
writeFileSync(join(web, "lib", "tool-logos.gen.ts"), ts);

const rows = meta.icons.map((i) => `| \`${i.slug}.svg\` | ${i.title} | ${i.file_url} | ${i.brand_source} | ${i.licence} | ${i.guidelines ?? "none listed"} | ${meta.retrieved} |`);
const md = `# Tool logos: sources and licences

Generated by \`web/scripts/gen-tool-logos.mjs\` from \`logos.json\`. Do not edit by hand.

Every SVG file in this folder is an unmodified icon from the **${meta.package}** package, version ${meta.version}
(${meta.package_url}), whose icon data is released under **${meta.package_licence}**. Where Simple Icons records a
different licence for one icon, the row says so (OpenTelemetry: CC-BY-4.0, artwork by the Cloud Native Computing
Foundation, used unchanged).

The logos are used nominatively: only to identify the tools this project runs on, in the architecture diagrams.
The shapes are not altered (the brand colour recorded by Simple Icons is applied as the fill), and they do not imply
that any owner endorses or is affiliated with this project. Each logo and name belongs to its owner.

| File | Tool | File source | Brand source recorded by Simple Icons | Licence | Brand guidelines | Retrieved |
|---|---|---|---|---|---|---|
${rows.join("\n")}

## Tools shown with a text badge instead of a logo

These tools have no entry in Simple Icons ${meta.version}. Their official marks were not vendored, because the
licence or trademark terms for reuse in a diagram were not verified for this release. The diagrams show a neutral
text badge with the tool's name instead; no logo was drawn or imitated.

${meta.badges.join(", ")}.
`;
writeFileSync(join(dir, "LOGOS_LICENSES.md"), md);
console.log(`tool logos: ${entries.length} files -> lib/tool-logos.gen.ts, LOGOS_LICENSES.md`);
