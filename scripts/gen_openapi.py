#!/usr/bin/env python3
"""Generate contracts/openapi.yaml from the FastAPI app. `--check` fails on drift (CI).

What it does:
    Builds the FastAPI app in memory (without reading .env) and dumps its OpenAPI description as YAML to
    contracts/openapi.yaml, with a "GENERATED, do not edit" header. With `--check` it only compares.

When to use it:
    After you change an API route, request model or response model. CI fails if the committed file drifts.

How to run:
    make openapi                                 (writes the file)
    uv run python scripts/gen_openapi.py --check (exit 1 if the file is out of date; writes nothing)

Inputs:
    The `falcon_api` package. No env vars needed.

Outputs / side effects:
    Overwrites contracts/openapi.yaml (without --check). No network, Redis or Postgres access.
    Review the diff: contracts are law and L1 owns them.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

from falcon_api.app import build_app
from falcon_core.config import Settings

OUT = Path(__file__).resolve().parents[1] / "contracts" / "openapi.yaml"
HEADER = "# GENERATED by scripts/gen_openapi.py from services/api. Do not edit by hand.\n"


def render() -> str:
    """Return the OpenAPI YAML text for the current FastAPI app, with the GENERATED header."""
    app = build_app(Settings(_env_file=None))  # type: ignore[call-arg]
    return HEADER + yaml.safe_dump(app.openapi(), sort_keys=True, allow_unicode=True, width=100)


def main() -> int:
    """Write contracts/openapi.yaml, or with --check only compare it; 1 if out of date."""
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("contracts/openapi.yaml is out of date: run `make openapi`", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
