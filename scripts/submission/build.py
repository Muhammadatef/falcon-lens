#!/usr/bin/env python3
"""`make submission`: build every form field and file of the submission into submission/.

Outputs:
    title.txt  description_en.txt  description_ar.txt  tools_used.txt  repo_url.txt
    deck.pptx  description.html  description.pdf  architecture.png (when the SVG exists)
    CHECKLIST.md

Every claim is tied to a capability detected in this checkout, every number comes from the
newest file in evals/results/published/, and the tools list comes from the lockfiles and the
compose file. The build fails (exit 1) when a description breaks the form limits, a wording
rule is broken, a file is over its size limit, the PDF is not 2 to 4 pages, or a number cannot
be traced.

It exits 0 with a loud NOT READY notice when the end-to-end check is not shipped yet, because
the files are still correct for that state. Set SUBMISSION_STRICT=1 to turn NOT READY into a
failure (use it for the real submission).

Run through the Makefile, which installs the pinned build tools:
    uv run --with-requirements scripts/submission/requirements.txt python scripts/submission/build.py
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

if __package__ in (None, ""):  # run as a script: make `submission` importable
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from submission import artifact as artifact_mod  # noqa: E402
from submission import capabilities as caps_mod  # noqa: E402
from submission import check_numbers, descriptions, tools_used  # noqa: E402
from submission import content as content_mod  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
MAX_FILE_BYTES = 20 * 1024 * 1024
ARCHITECTURE_SVG = "docs/assets/architecture.svg"


def repo_url(root: Path) -> str:
    """Public https URL of `origin`, without credentials or a `.git` suffix."""
    try:
        raw = subprocess.run(  # noqa: S603
            ["git", "-C", str(root), "remote", "get-url", "origin"],  # noqa: S607
            capture_output=True, text=True, check=True, timeout=10,
        ).stdout.strip()  # fmt: skip
    except (subprocess.SubprocessError, OSError):
        return ""
    return normalise_repo_url(raw)


def normalise_repo_url(raw: str) -> str:
    raw = raw.strip()
    match = re.match(r"^(?:ssh://)?git@([^:/]+)[:/](.+)$", raw)
    if match:
        raw = f"https://{match.group(1)}/{match.group(2)}"
    raw = re.sub(r"^(https?://)[^@/]+@", r"\1", raw)
    return re.sub(r"\.git$", "", raw)


def size_line(path: Path) -> tuple[str, bool]:
    size = path.stat().st_size
    ok = size <= MAX_FILE_BYTES
    human = f"{size / 1024:.0f} KB" if size < 1024 * 1024 else f"{size / 1024 / 1024:.1f} MB"
    return f"{human} ({size} bytes)", ok


def checklist(out: Path, root: Path, caps: dict[str, bool], artifact: artifact_mod.Artifact | None, problems: list[str], pages: int | None) -> str:
    def text(name: str) -> str:
        return (out / name).read_text(encoding="utf-8").strip()

    ready = content_mod.mvp_shipped(caps) and not problems
    lines = [
        "# Submission checklist",
        "",
        "Generated by `make submission`. Do not edit: rebuild instead.",
        "",
        f"**State: {'READY for the owner checks below' if ready else 'NOT READY'}**",
        "",
    ]
    if not content_mod.mvp_shipped(caps):
        lines += ["> NOT READY: the end-to-end URL check is not detected in this checkout (organiser rule: a working MVP). Rebuild after gate G4.", ""]
    for problem in problems:
        lines.append(f"> PROBLEM: {problem}")
    if problems:
        lines.append("")

    lines += ["## Form fields", "", "| Field | Source file | Length | Check |", "|---|---|---|---|"]
    for name, limit in (("title.txt", None), ("description_en.txt", descriptions.MAX_CHARS), ("description_ar.txt", descriptions.MAX_CHARS), ("tools_used.txt", None), ("repo_url.txt", None)):
        value = text(name)
        length = descriptions.count_chars(value)
        if limit:
            errors = descriptions.check(value)
            state = "ok" if not errors else "FAIL: " + "; ".join(errors)
            lines.append(f"| {name.removesuffix('.txt')} | `submission/{name}` | {length} of {limit} characters | {state} |")
        else:
            lines.append(f"| {name.removesuffix('.txt')} | `submission/{name}` | {length} characters | {'ok' if value else 'FAIL: empty'} |")
    lines += ["| video | recorded by the owner | see the shot list in `docs/DEMO.md` | owner |", ""]

    lines += ["## Files", "", "| File | Size | Limit | Check |", "|---|---|---|---|"]
    for name in ("deck.pptx", "description.pdf"):
        path = out / name
        if path.is_file():
            human, ok = size_line(path)
            extra = f", {pages} pages (2 to 4 expected)" if name.endswith(".pdf") and pages is not None else ""
            lines.append(f"| `submission/{name}` | {human}{extra} | 20 MB | {'ok' if ok else 'FAIL'} |")
        else:
            lines.append(f"| `submission/{name}` | missing | 20 MB | FAIL |")
    lines.append("")

    lines += ["## Numbers", ""]
    if artifact:
        lines.append(f"- Source artifact: `evals/results/published/{artifact.path.name}`. Every number in the deck, the PDF and the README was traced to it by `scripts/submission/check_numbers.py`.")
    else:
        lines.append("- No published eval artifact. The deck and the PDF say \"Evaluation in progress\" and contain no statistic. Rebuild after `make eval` has published one.")
    lines.append("")

    lines += [
        "## Capabilities claimed",
        "",
        "A claim is made only for a capability marked shipped. The probes are necessary conditions, not proof, so confirm each shipped row on the running stack with the DEMO.md section named.",
        "",
        "| Capability | Detected | Confirm with | Probes |",
        "|---|---|---|---|",
    ]
    for cap, shipped, results in caps_mod.probe_report(root):
        probes = "<br>".join(f"{'ok' if ok else 'missing'}: `{spec}`" for spec, ok in results)
        lines.append(f"| {cap.label} | {'shipped' if shipped else 'not shipped (marked PLANNED, listed on the roadmap)'} | {cap.demo or 'n/a'} | {probes} |")
    lines.append("")

    lines += [
        "## Owner checks before upload",
        "",
        "- [ ] `SUBMISSION_STRICT=1 make submission` exits 0 on the commit being submitted.",
        "- [ ] Open each link in a private window (not signed in): the repository URL, the demo URL, the video link, every link in the README. Each must load without a login.",
        "- [ ] The repository is public and `make scan` and `make guard` are clean on the submitted commit.",
        "- [ ] Read both descriptions aloud once. Arabic reviewed by a native speaker.",
        "- [ ] Open `deck.pptx` in PowerPoint or Keynote: Arabic lines read right to left, no text overflows a card.",
        "- [ ] Replace the placeholder names on the Team slide.",
        "- [ ] No Abu Dhabi Police logo or branding anywhere; the independence line is on every slide header.",
        "- [ ] The video is the real screen with the owner's own voice (no AI video or voice), follows the shot list in `docs/DEMO.md`, and shows the REPLAY and TEST FIXTURE labels where they apply.",
        "- [ ] Every statistic said in the video or the pitch is in the published eval artifact or has a public source link.",
        "- [ ] File sizes above are within the limits of the submission form.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build the submission package.")
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--out", type=Path, default=None, help="default: <root>/submission")
    parser.add_argument("--text-only", action="store_true", help="only the text fields and the checklist (no deck, no PDF)")
    args = parser.parse_args(argv)

    root = args.root.resolve()
    out = (args.out or root / "submission").resolve()
    out.mkdir(parents=True, exist_ok=True)
    problems: list[str] = []

    caps = caps_mod.detect(root)
    artifact = artifact_mod.load(root / "evals" / "results" / "published")
    url = repo_url(root)
    if not url:
        problems.append("repo_url.txt is empty: no `origin` remote found")

    (out / "title.txt").write_text(descriptions.TITLE + "\n", encoding="utf-8")
    texts = {}
    for lang in ("en", "ar"):
        texts[lang] = descriptions.compose(caps, lang)
        (out / f"description_{lang}.txt").write_text(texts[lang] + "\n", encoding="utf-8")
        problems += [f"description_{lang}.txt: {error}" for error in descriptions.check(texts[lang])]
    (out / "tools_used.txt").write_text(tools_used.render(root), encoding="utf-8")
    (out / "repo_url.txt").write_text(url + "\n", encoding="utf-8")

    sections = content_mod.build(caps, artifact, url)
    problems += [f"deck/document wording: {error}" for error in descriptions.wording_errors(content_mod.all_text(sections))]

    pages: int | None = None
    if not args.text_only:
        from submission import deck, document  # noqa: PLC0415  (need python-pptx and playwright)

        png: Path | None = None
        svg = root / ARCHITECTURE_SVG
        if svg.is_file():
            png = document.render_svg_png(svg, out / "architecture.png")
        else:
            print(f"WARNING: {ARCHITECTURE_SVG} is not in this checkout; the deck uses the built-in block diagram instead.", file=sys.stderr)
        mvp = content_mod.mvp_shipped(caps)
        deck.build(sections, out / "deck.pptx", png, mvp)
        html_path = out / "description.html"
        html_path.write_text(document.build_html(sections, texts["en"], texts["ar"], tools_used.names(root), png, mvp, root), encoding="utf-8")
        document.render_pdf(html_path, out / "description.pdf")
        pages = document.page_count(out / "description.pdf")
        if not document.MIN_PAGES <= pages <= document.MAX_PAGES:
            problems.append(f"description.pdf has {pages} pages, expected {document.MIN_PAGES} to {document.MAX_PAGES}")
        for name in ("deck.pptx", "description.pdf"):
            human, ok = size_line(out / name)
            if not ok:
                problems.append(f"{name} is {human}, over the 20 MB limit")

        traceable = check_numbers.Traceable(artifact.data if artifact else None)
        sources, missing = check_numbers.collect_sources(root, out, require_package=True)
        problems += missing
        for name, text in sources:
            for finding in check_numbers.find_untraceable(text, traceable, name):
                problems.append(f"untraceable number: {finding}")

    (out / "CHECKLIST.md").write_text(checklist(out, root, caps, artifact, problems, pages), encoding="utf-8")

    print(f"submission package: {out}")
    for name in sorted(p.name for p in out.iterdir() if p.is_file() and not p.name.startswith(".")):
        print(f"  {name}")
    for lang in ("en", "ar"):
        print(f"description_{lang}: {descriptions.count_chars(texts[lang])}/{descriptions.MAX_CHARS} characters")
    for problem in problems:
        print(f"ERROR: {problem}", file=sys.stderr)
    if problems:
        return 1
    if not content_mod.mvp_shipped(caps):
        print("\n" + "#" * 78, file=sys.stderr)
        print("# NOT READY: the end-to-end check is not shipped in this checkout.", file=sys.stderr)
        print("# The files describe that state truthfully. Do not submit them. Rebuild after G4.", file=sys.stderr)
        print("#" * 78, file=sys.stderr)
        if os.environ.get("SUBMISSION_STRICT") == "1":
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
