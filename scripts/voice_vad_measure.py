#!/usr/bin/env python3
"""Measure how often a shorter end-of-speech silence would cut an utterance in two (false cut-offs).

What it does:
    Speaks every sentence of the voice bench set with macOS `say` (English voices and the Arabic voice Majed), cuts the
    audio into the same 30 ms frames as web/lib/vad.ts, applies its voiced rule (RMS above max(0.02, 3 x floor)) and
    finds the longest silence INSIDE each utterance. An utterance is falsely cut when that pause is at least the
    configured end-of-speech silence. Writes evals/results/published/voice/vad_silence_<UTC>.json, labelled SYNTHETIC
    (TTS pauses are mechanical: real people hesitate more, so this is a lower bound).
How to run:
    uv run python scripts/voice_vad_measure.py [--no-publish]
Needs macOS `say` and ffmpeg.
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
import wave
from datetime import UTC, datetime
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from voice_bench import AR_VOICE, EN_VOICES, OUT, SET, tts  # noqa: E402

FRAME_MS = 30
MIN_THRESHOLD = 0.02
CANDIDATES_MS = (500, 600, 650, 800)


def longest_inner_pause_ms(wav: np.ndarray, rate: int) -> int:
    n = int(rate * FRAME_MS / 1000)
    frames = wav[: len(wav) // n * n].reshape(-1, n)
    rms = np.sqrt((frames**2).mean(axis=1))
    voiced = rms > MIN_THRESHOLD
    idx = np.flatnonzero(voiced)
    if len(idx) < 2:
        return 0
    inner = voiced[idx[0] : idx[-1] + 1]
    best = run = 0
    for v in inner:
        run = 0 if v else run + 1
        best = max(best, run)
    return best * FRAME_MS


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--no-publish", action="store_true")
    a = ap.parse_args()
    pauses: dict[str, list[int]] = {"en": [], "ar": []}
    with tempfile.TemporaryDirectory() as td:
        d = Path(td)
        for i, (lang, text, _wake, _intent) in enumerate(SET):
            for voice in EN_VOICES if lang == "en" else (AR_VOICE,):
                wav_path = tts(text, voice, d, f"c{i}_{voice}")
                with wave.open(str(wav_path), "rb") as w:
                    rate = w.getframerate()
                    data = np.frombuffer(w.readframes(w.getnframes()), dtype="<i2").astype(np.float32) / 32768.0
                pauses[lang].append(longest_inner_pause_ms(data, rate))
    out = {
        "kind": "voice_vad_silence",
        "provenance": "SYNTHETIC: speech generated by macOS `say` (TTS), not human recordings. Real speech has longer hesitations.",  # noqa: E501
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "frame_ms": FRAME_MS,
        "utterances": {k: len(v) for k, v in pauses.items()},
        "longest_inner_pause_ms": {k: {"max": max(v), "p95": int(np.percentile(v, 95))} for k, v in pauses.items()},
        "false_cutoffs_by_silence_ms": {
            str(c): {k: sum(1 for p in v if p >= c) for k, v in pauses.items()} for c in CANDIDATES_MS
        },
    }
    print(json.dumps(out, indent=1))
    if not a.no_publish:
        OUT.mkdir(parents=True, exist_ok=True)
        path = OUT / f"vad_silence_{datetime.now(UTC).strftime('%Y%m%dT%H%M%SZ')}.json"
        path.write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
        print("wrote", path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
