def runtime_deps(root: Path = ROOT) -> set[str]:
    """Normalised runtime dependency names of every service and package pyproject."""
    out: set[str] = set()
    for path in sorted([*root.glob("services/*/pyproject.toml"), *root.glob("packages/*/pyproject.toml")]):
        for dep in tomllib.loads(path.read_text(encoding="utf-8")).get("project", {}).get("dependencies", []):
            m = re.match(r"[A-Za-z0-9_.-]+", dep)
            if m:
                out.add(m.group(0).lower().replace("_", "-"))
    return out


def _lock_version(root: Path, name: str) -> str:
    lock = tomllib.loads((root / "uv.lock").read_text(encoding="utf-8"))
    return next((p.get("version", "") for p in lock.get("package", []) if p["name"] == name), "")


def _load_tools() -> Any:
    spec = importlib.util.spec_from_file_location("tools_used", ROOT / "scripts/submission/tools_used.py")
    if spec is None or spec.loader is None:
        raise SystemExit("readme_stack: cannot load tools_used")
    mod = importlib.util.module_from_spec(spec)
    sys.modules["tools_used"] = mod
    spec.loader.exec_module(mod)
    return mod


def _badge(label: str, message: str, color: str, logo: str | None) -> str:
    def esc(text: str) -> str:
        return quote(text.replace("-", "--").replace("_", "__").replace(" ", "_"), safe="_-")

    url = f"https://img.shields.io/badge/{esc(label)}-{esc(message or ' ')}-{color}?style=flat-square"
    if logo:
        url += f"&logo={logo}&logoColor=white"
    alt = f"{label} {message}".strip()
    return f'<img src="{url}" alt="{alt}">'


def _models() -> list[tuple[str, str]]:
    """(label, note) for model names found in the shipped defaults."""
    out: list[tuple[str, str]] = []
    cfg = ROOT / "packages/falcon_core/src/falcon_core/config.py"
    text = cfg.read_text(encoding="utf-8") if cfg.is_file() else ""
    for family in ("sonnet", "haiku"):
        m = re.search(rf'"claude-{family}-(\d+)-(\d+)"', text)
        if m:
            out.append((f"Claude {family.title()}", f"{m.group(1)}.{m.group(2)}"))
    llm = ROOT / "packages/falcon_core/src/falcon_core/llm/config.py"
    if re.search(r'"inkling-2-mini', llm.read_text(encoding="utf-8") if llm.is_file() else ""):
        out.append(("Inkling 2 Mini (local)", "via Ollama"))
    return out


def _licence() -> tuple[str, str]:
    for name in ("LICENSE", "LICENSE.md", "LICENSE.txt"):
        path = ROOT / name
        if path.is_file():
            head = path.read_text(encoding="utf-8")[:400]
            for needle, spdx in (("MIT License", "MIT"), ("Apache License", "Apache-2.0"), ("GNU GENERAL", "GPL")):
                if needle in head:
                    return "License", spdx
            return "License", "see LICENSE"
    return "License", "not chosen yet"


def render() -> str:
    tu = _load_tools()
    versions: dict[str, str] = {}
    for _title, versioned in tu.categories(ROOT):
        for v in versioned:
            bare = re.sub(r"\s+\d[\d.]*$", "", v)
            versions[bare] = v[len(bare) :].strip()
    rows: dict[str, list[str]] = {g: [] for g in GROUPS}
    seen: set[str] = set()
    for _title, items in tu.names(ROOT):
        for item in items:
            key = item.lower()
            if key in SKIP or key in seen:
                continue
            seen.add(key)
            group, logo, color = KNOWN.get(key, ("Backend", "", "555555"))
            label = LABELS.get(item, item)
            rows[group].append(_badge(label, versions.get(item, ""), color, logo or None))
    deps = runtime_deps(ROOT)
    for dep, (label, group, logo, color) in EXTRA_DEPS.items():
        if dep in deps:
            rows[group].append(_badge(label, _lock_version(ROOT, dep), color, logo))
    for label, msg in _models():
        rows["AI agent stack"].append(_badge(label, msg, "D97757" if "Claude" in label else "000000", None))
    makefile = ROOT / "Makefile"
    if makefile.is_file() and "cloudflared" in makefile.read_text(encoding="utf-8"):
        rows["Infrastructure"].append(_badge("Cloudflare Tunnel", "", "F38020", "cloudflare"))
    lic_label, lic_msg = _licence()
    rows["Licence"].append(_badge(lic_label, lic_msg, "lightgrey" if "not" in lic_msg else "blue", None))
    lines = [START, ""]
    for group in GROUPS:
        if rows[group]:
            lines.append(f'<p align="center"><sub>{group}</sub><br>{" ".join(rows[group])}</p>')
    lines += ["", END]
    return "\n".join(lines)


def apply(text: str, block: str) -> str:
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit("readme_stack: markers not found in README.md")
    return pattern.sub(lambda _m: block, text)


def main(argv: list[str]) -> int:
    current = README.read_text(encoding="utf-8")
    updated = apply(current, render())
    if "--check" in argv:
        if updated != current:
            print("readme_stack: README badges out of date; run scripts/readme_stack.py", file=sys.stderr)
            return 1
        print("readme_stack: ok")
        return 0
    README.write_text(updated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
